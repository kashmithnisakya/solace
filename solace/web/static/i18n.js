const LANGS = ["en", "si"];

function savedLang() {
  try {
    const v = localStorage.getItem("solace.lang");
    if (LANGS.includes(v)) return v;
  } catch { /* private mode */ }
  return (navigator.language || "").toLowerCase().startsWith("si") ? "si" : "en";
}

let LANG = savedLang();

function t(key, vars = {}) {
  const text = STRINGS[LANG][key] ?? STRINGS.en[key] ?? key;
  return text.replace(/\{(\w+)\}/g, (_, k) => (vars[k] ?? `{${k}}`));
}

/* Fill every element marked with data-i18n (text), data-i18n-placeholder and data-i18n-aria. */
function applyI18n(root = document) {
  document.documentElement.lang = LANG;
  root.querySelectorAll("[data-i18n]").forEach((n) => { n.textContent = t(n.dataset.i18n); });
  root.querySelectorAll("[data-i18n-placeholder]").forEach((n) => { n.placeholder = t(n.dataset.i18nPlaceholder); });
  root.querySelectorAll("[data-i18n-aria]").forEach((n) => { n.setAttribute("aria-label", t(n.dataset.i18nAria)); });
}

function setLang(lang) {
  LANG = LANGS.includes(lang) ? lang : "en";
  try { localStorage.setItem("solace.lang", LANG); } catch { /* private mode */ }
  applyI18n();
}
